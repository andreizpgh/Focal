#!/usr/bin/env python3
"""Derive Android/docs assets from the user-approved Focus wave sources."""

import argparse
from copy import deepcopy
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from PIL import Image

BRAND = Path(__file__).resolve().parent
ROOT = BRAND.parents[1]
SOURCE = BRAND / "source"
SVG = "http://www.w3.org/2000/svg"
ANDROID = "http://schemas.android.com/apk/res/android"
ET.register_namespace("", SVG)


def tag(name):
    return f"{{{SVG}}}{name}"


def number(value):
    return f"{float(value):.8f}".rstrip("0").rstrip(".")


def xml_bytes(element):
    return ET.tostring(element, encoding="utf-8", xml_declaration=True) + b"\n"


def svg_document(viewbox, width, height):
    return ET.Element(tag("svg"), {
        "viewBox": viewbox, "width": str(width), "height": str(height),
    })


def pair_kerning(font, first, second):
    if "GPOS" not in font:
        return 0
    table = font["GPOS"].table
    indices = {index for record in table.FeatureList.FeatureRecord
               if record.FeatureTag == "kern"
               for index in record.Feature.LookupListIndex}
    advance = 0
    for index in sorted(indices):
        lookup = table.LookupList.Lookup[index]
        for subtable in lookup.SubTable:
            if lookup.LookupType == 9:
                subtable = subtable.ExtSubTable
            if first not in subtable.Coverage.glyphs:
                continue
            value = None
            if subtable.Format == 1:
                pairs = subtable.PairSet[subtable.Coverage.glyphs.index(first)]
                value = next((pair.Value1 for pair in pairs.PairValueRecord
                              if pair.SecondGlyph == second), None)
            elif subtable.Format == 2:
                class1 = subtable.ClassDef1.classDefs.get(first, 0)
                class2 = subtable.ClassDef2.classDefs.get(second, 0)
                value = subtable.Class1Record[class1].Class2Record[class2].Value1
            if value:
                advance += getattr(value, "XAdvance", 0)
    return advance


def outline_lockup(source, font):
    document = ET.parse(source).getroot()
    text = document.find(tag("text"))
    if text is None or text.text != "Focal":
        raise ValueError(f"Unexpected wordmark in {source}")
    glyphs = font.getGlyphSet()
    names = [font.getBestCmap()[ord(character)] for character in text.text]
    scale = float(text.get("font-size")) / font["head"].unitsPerEm
    group = ET.Element(tag("g"), {
        "fill": text.get("fill"),
        "aria-label": "Focal",
        "transform": (f"translate({text.get('x')} {text.get('y')}) "
                      f"scale({number(scale)} {number(-scale)})"),
    })
    position = 0
    tracking = float(text.get("letter-spacing", "0")) / scale
    for index, name in enumerate(names):
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(pen)
        ET.SubElement(group, tag("path"), {
            "d": pen.getCommands(),
            "transform": f"translate({number(position)} 0)",
        })
        position += font["hmtx"].metrics[name][0] + tracking
        if index + 1 < len(names):
            position += pair_kerning(font, name, names[index + 1])
    index = list(document).index(text)
    document.remove(text)
    document.insert(index, group)
    assert not list(document.iter(tag("text")))
    return xml_bytes(document)


def pill_path(bar):
    x, y, width, height = (float(bar.get(key)) for key in ("x", "y", "width", "height"))
    r = width / 2
    # Quarter-circle arcs preserve the author's fully rounded 3.2-unit strokes.
    return (f"M{number(x+r)},{number(y)}"
            f"A{number(r)},{number(r)} 0 0 1 {number(x+width)},{number(y+r)}"
            f"V{number(y+height-r)}"
            f"A{number(r)},{number(r)} 0 0 1 {number(x+r)},{number(y+height)}"
            f"A{number(r)},{number(r)} 0 0 1 {number(x)},{number(y+height-r)}"
            f"V{number(y+r)}"
            f"A{number(r)},{number(r)} 0 0 1 {number(x+r)},{number(y)}Z")


def vector_xml(bars, notification=False):
    size = 24 if notification else 108
    color = "#FFFFFF" if notification else "#000000"
    lines = ["<!-- Generated by design/brand/build.py; edit the approved source, not this file. -->",
             f'<vector xmlns:android="{ANDROID}" android:width="{size}dp" '
             f'android:height="{size}dp" android:viewportWidth="{size}" '
             f'android:viewportHeight="{size}">']
    if notification:
        lines.append('    <group android:scaleX="0.3787878788" android:scaleY="0.3787878788" '
                     'android:translateX="-8.4545454545" android:translateY="-8.4545454545">')
    indent = "        " if notification else "    "
    for bar in bars:
        alpha = "" if notification else f' android:fillAlpha="{bar.get("opacity")}"'
        lines.append(f'{indent}<path android:fillColor="{color}"{alpha} android:pathData="{pill_path(bar)}" />')
    if notification:
        lines.append("    </group>")
    lines.append("</vector>")
    return ("\n".join(lines) + "\n").encode()


def flat_svg(bars, notification=False):
    size = 24 if notification else 108
    document = svg_document(f"0 0 {size} {size}", size, size)
    group = ET.SubElement(document, tag("g"), {"fill": "#fff" if notification else "#000"})
    if notification:
        group.set("transform", "translate(-8.4545454545 -8.4545454545) scale(.3787878788)")
    for bar in bars:
        attributes = {"d": pill_path(bar)}
        if not notification:
            attributes["opacity"] = bar.get("opacity")
        ET.SubElement(group, tag("path"), attributes)
    return document


def connected_components(image):
    alpha = image.convert("RGBA").getchannel("A")
    remaining = {(x, y) for y in range(image.height) for x in range(image.width)
                 if alpha.getpixel((x, y)) >= 128}
    count = 0
    while remaining:
        count += 1
        stack = [remaining.pop()]
        while stack:
            x, y = stack.pop()
            for neighbour in ((x-1, y), (x+1, y), (x, y-1), (x, y+1)):
                if neighbour in remaining:
                    remaining.remove(neighbour)
                    stack.append(neighbour)
    return count


def build(check):
    canonical = SOURCE / "focal-icon-render.svg"
    document = ET.parse(canonical).getroot()
    clipped = document.find(tag("g"))
    definitions = clipped.findall(tag("defs"))
    bars = [rect for rect in clipped.findall(tag("rect")) if rect.get("x") is not None]
    backgrounds = [rect for rect in clipped.findall(tag("rect")) if rect.get("x") is None]
    if len(bars) != 9 or len(definitions) != 2 or len(backgrounds) != 3:
        raise ValueError("Unexpected approved render structure")
    expected_heights = [7, 12, 19, 30, 40, 30, 19, 12, 7]
    expected_alpha = [.18, .3, .5, .75, 1, .75, .5, .3, .18]
    for index, bar in enumerate(bars):
        assert abs(float(bar.get("x")) - (27.6 + index * 6.2)) < 1e-6
        assert float(bar.get("width")) == 3.2
        assert float(bar.get("height")) == expected_heights[index]
        assert float(bar.get("opacity")) == expected_alpha[index]

    foreground = svg_document("0 0 108 108", 432, 432)
    foreground.append(deepcopy(definitions[1]))
    foreground.extend(deepcopy(bars))
    background = svg_document("0 0 108 108", 432, 432)
    background.append(deepcopy(definitions[0]))
    background.extend(deepcopy(backgrounds))
    # Documentation proof uses the same central 72-unit crop as the supplied render,
    # but without its baked rounded-square clip or decorative outer rim.
    preview = svg_document("18 18 72 72", 720, 720)
    preview.extend(deepcopy(list(background)))
    preview.extend(deepcopy(list(foreground)))

    font_path = ROOT / "design/explorations/assets/Inter.woff2"
    font = instantiateVariableFont(TTFont(font_path), {"wght": 600}, inplace=False)
    outputs = {
        "design/brand/generated/launcher-foreground.svg": xml_bytes(foreground),
        "design/brand/generated/launcher-background.svg": xml_bytes(background),
        "design/brand/generated/launcher-preview.svg": xml_bytes(preview),
        "design/brand/generated/focal-mono.svg": xml_bytes(flat_svg(bars)),
        "design/brand/generated/focal-notification.svg": xml_bytes(flat_svg(bars, True)),
        "app/src/main/res/drawable/ic_focal_mono.xml": vector_xml(bars),
        "app/src/main/res/drawable/ic_notification.xml": vector_xml(bars, True),
        "docs/mark.svg": canonical.read_bytes(),
        "docs/mark-preview.png": (SOURCE / "focal-icon-render.png").read_bytes(),
        "design/brand/Inter-LICENSE.txt": (ROOT / "design/explorations/assets/Inter-LICENSE.txt").read_bytes(),
    }
    for variant in ("dark", "light"):
        outputs[f"design/brand/generated/focal-lockup-{variant}-outlined.svg"] = outline_lockup(
            SOURCE / f"focal-lockup-{variant}.svg", font)
    bitmap = ('<!-- Generated by design/brand/build.py. -->\n'
              '<bitmap xmlns:android="' + ANDROID + '"\n'
              '    android:src="@drawable/{}" android:gravity="fill" android:filter="true" />\n')
    outputs["app/src/main/res/drawable/ic_focal.xml"] = bitmap.format("focal_launcher_foreground").encode()
    outputs["app/src/main/res/drawable/ic_focal_background.xml"] = bitmap.format("focal_launcher_background").encode()
    outputs["app/src/main/res/mipmap-anydpi/ic_launcher.xml"] = (
        '<!-- Generated by design/brand/build.py. -->\n'
        f'<adaptive-icon xmlns:android="{ANDROID}">\n'
        '    <background android:drawable="@drawable/ic_focal_background" />\n'
        '    <foreground android:drawable="@drawable/ic_focal" />\n'
        '    <monochrome android:drawable="@drawable/ic_focal_mono" />\n'
        '</adaptive-icon>\n').encode()

    render_jobs = [
        ("launcher-foreground.svg", "app/src/main/res/drawable-xxxhdpi/focal_launcher_foreground.png", 432, 432),
        ("launcher-background.svg", "app/src/main/res/drawable-xxxhdpi/focal_launcher_background.png", 432, 432),
        ("launcher-preview.svg", "design/brand/generated/launcher-preview.png", 720, 720),
        ("focal-notification.svg", "design/brand/generated/notification-24.png", 24, 24),
        ("focal-mono.svg", "design/brand/generated/monochrome-48.png", 48, 48),
        ("focal-lockup-light-outlined.svg", "design/brand/generated/focal-lockup-light-outlined.png", 467, 150),
        ("focal-lockup-dark-outlined.svg", "design/brand/generated/focal-lockup-dark-outlined.png", 467, 150),
    ]
    executable = os.environ.get("FOCAL_CHROMIUM") or shutil.which("chromium") or shutil.which("google-chrome")
    if not executable:
        raise RuntimeError("Install Chromium or set FOCAL_CHROMIUM to its executable")
    with tempfile.TemporaryDirectory(prefix="focal-brand-") as temp:
        staging = Path(temp)
        for name, data in outputs.items():
            target = staging / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        jobs = []
        for source, destination, width, height in render_jobs:
            target = staging / destination
            target.parent.mkdir(parents=True, exist_ok=True)
            jobs.append({"input": str(staging / "design/brand/generated" / source),
                         "output": str(target), "width": width, "height": height})
        request = staging / "render.json"
        request.write_text(json.dumps({"executable": executable, "jobs": jobs}))
        result = subprocess.run(["node", str(BRAND / "render.cjs"), str(request)],
                                capture_output=True, text=True)
        if result.returncode:
            raise RuntimeError("Chromium renderer failed:\n" + result.stderr)
        renderer = json.loads(result.stdout)
        for _, name, width, height in render_jobs:
            target = staging / name
            image = Image.open(target)
            assert image.size == (width, height), name
            outputs[name] = target.read_bytes()

        fg = Image.open(staging / "app/src/main/res/drawable-xxxhdpi/focal_launcher_foreground.png").convert("RGBA")
        bg = Image.open(staging / "app/src/main/res/drawable-xxxhdpi/focal_launcher_background.png").convert("RGBA")
        for point in ((0, 0), (431, 0), (0, 431), (431, 431)):
            assert fg.getpixel(point)[3] == 0, "Foreground must be transparent at canvas corners"
        assert bg.getchannel("A").getextrema() == (255, 255), "Background must be full bleed and opaque"
        notification = Image.open(staging / "design/brand/generated/notification-24.png")
        components = connected_components(notification)
        assert components == 9, f"Expected nine separate notification strokes; found {components}"

        manifest = {
            "canonical_source": "design/brand/source/focal-icon-render.svg",
            "source_sha256": hashlib.sha256(canonical.read_bytes()).hexdigest(),
            "inter_sha256": hashlib.sha256(font_path.read_bytes()).hexdigest(),
            "inter_version": font["name"].getDebugName(5),
            "renderer": renderer,
            "notification_components_at_24px": components,
            "outputs_sha256": {name: hashlib.sha256(data).hexdigest()
                               for name, data in sorted(outputs.items())},
        }
        outputs["design/brand/generated/manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()

    stale = []
    for name, data in outputs.items():
        target = ROOT / name
        if check:
            if not target.exists() or target.read_bytes() != data:
                stale.append(name)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            if not target.exists() or target.read_bytes() != data:
                target.write_bytes(data)
    if stale:
        raise SystemExit("Stale generated brand assets:\n" + "\n".join(stale))
    print(f"{'Checked' if check else 'Generated'} {len(outputs)} assets; notification 24px: nine separate strokes; Chromium {renderer['chromium']}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check derived files without changing them")
    build(parser.parse_args().check)
